-- zero -- "Skill Talent: None" -- Entertainer/Doctor/Athlete each have 2 groups, everything else 1),
-- 95 Origin group-option rows (Raring to Go's single group has no restricted list -- "choose any one
-- skill" -- so all 18 skills are its options).

