-- Why it was lost: the original parse read the two-column pages naively and only followed a wrapped line when the
-- previous one ended in "/", "-" or ",". The Biology line ("... Egg Hatch Rate - 10" / "Days, Diet - ..., Habitat -
-- ...") and long Proficiencies lists wrap without one, so Diet, the later Habitats and the later Proficiencies were
-- dropped; letter-suffixed Elemental Attacks (EF / EI / FI) were dropped too.
--
-- This pass re-read all 814 pages column by column (stat column first on mirrored pages), with each family's Biology
-- and Proficiencies block assigned to the species of that family, and kept a value only when it maps to an existing
-- reference row. Mapping rules as 20261122200000: Claws / Blades -> Slashing, Fang -> Fangs, Munitions -> Munition,
-- Piscean -> Piscian, Elemental Attack letter suffixes split per letter (E = Electric, F = Fire, I = Ice);
-- form-qualified proficiencies ("Horned (Nidoqueen)") only for the named species, restrictions only when the variant
-- exists ("Ice (Melee attacks)" -> Ice (Melee), "Martial (No Punches/Kicks)" -> Martial (No Punches or Kicks)), others
-- ("Grass (Ranged attacks)") left out. Habitats: singular -> plural, Urban Plant -> Urban Plants, Urban Abandoned ->
-- Abandoned, Urban Burial -> Burial, Deep Caves -> Caves, Unknown / Variable -> none.
--
-- Additive only: fills empty fields, and adds the values the book lists that a species is missing. Species whose
-- existing data disagrees with the book (rather than being a subset of it) are left alone here and logged in
-- [[Improvement - Re-verify the original 351 species against PTA3Pokedex.pdf]].
-- Every row is looked up by name (global rows only: campaign_id is null), never by id.

