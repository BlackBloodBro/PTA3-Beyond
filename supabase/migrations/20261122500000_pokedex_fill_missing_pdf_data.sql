-- Mew, missed by [[Improvement - Fill in the last 23 Legendary and Mythical Pokedex entries from the GM's Guide]]:
-- PTA3GameMastersGuide.pdf p. 163 (right column) -- Psychic - Small (Size), Light (Weight); Biology: Diet - Omnivore,
-- Habitat - Forest / Mountain / Rainforest (-> Forests, Mountains, Jungles). Its Proficiencies are prose ("Mew can know
-- any move"), so none, like Silvally.
update pokedex set size_id = (select id from sizes where name = 'Small'), weight_id = (select id from weights where name = 'Light')
where name = 'Mew' and campaign_id is null and size_id is null;
insert into pokedex_diets (pokedex_id, diet_id)
select p.id, d.id from pokedex p join diets d on d.name = 'Omnivore'
where p.name = 'Mew' and p.campaign_id is null
  and not exists (select 1 from pokedex_diets x where x.pokedex_id = p.id and x.diet_id = d.id);
insert into pokedex_habitats (pokedex_id, habitat_id)
select p.id, h.id from pokedex p join habitats h on h.name in ('Forests', 'Mountains', 'Jungles')
where p.name = 'Mew' and p.campaign_id is null
  and not exists (select 1 from pokedex_habitats x where x.pokedex_id = p.id and x.habitat_id = h.id);
